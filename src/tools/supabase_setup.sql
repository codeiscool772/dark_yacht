create table if not exists public.links (
    id bigint generated by default as identity primary key,
    url text not null check (length(url) between 1 and 2048),
    tag text not null check (length(tag) between 1 and 24),
    likes integer not null default 0 check (likes >= 0),
    reports integer not null default 0 check (reports >= 0),
    created_at timestamptz not null default now()
);

create table if not exists public.link_admins (
    user_id uuid primary key references auth.users(id) on delete cascade
);

alter table public.links enable row level security;
alter table public.link_admins enable row level security;

revoke all on public.links from anon, authenticated;
grant select on public.links to anon, authenticated;
grant insert (url, tag) on public.links to anon, authenticated;
grant delete on public.links to authenticated;

drop policy if exists "Anyone can read links" on public.links;
create policy "Anyone can read links"
    on public.links for select to anon, authenticated
    using (true);

drop policy if exists "Anyone can submit links" on public.links;
create policy "Anyone can submit links"
    on public.links for insert to anon, authenticated
    with check (true);

create or replace function public.is_link_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.link_admins
        where user_id = (select auth.uid())
    );
$$;

revoke all on function public.is_link_admin() from public;
grant execute on function public.is_link_admin() to authenticated;

create or replace function public.update_link_metric(
    p_id bigint,
    p_metric text,
    p_delta integer
)
returns public.links
language plpgsql
security definer
set search_path = ''
as $$
declare
    updated_link public.links;
begin
    if p_metric is null
        or p_metric not in ('likes', 'reports')
        or p_delta is null
        or p_delta not between -2 and 2
        or p_delta = 0
        or (p_metric = 'reports' and abs(p_delta) <> 1) then
        raise exception 'Invalid metric update';
    end if;

    update public.links
    set likes = case
            when p_metric = 'likes' then greatest(0, likes + p_delta)
            else likes
        end,
        reports = case
            when p_metric = 'reports' then greatest(0, reports + p_delta)
            else reports
        end
    where id = p_id
    returning * into updated_link;

    if not found then
        raise exception 'That link is gone. Refresh.';
    end if;

    return updated_link;
end;
$$;

revoke all on function public.update_link_metric(bigint, text, integer) from public;
grant execute on function public.update_link_metric(bigint, text, integer) to anon, authenticated;

drop policy if exists "Admins can delete links" on public.links;
create policy "Admins can delete links"
    on public.links for delete to authenticated
    using ((select public.is_link_admin()));

create or replace function public.retag_links(p_from text, p_to text)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
    changed integer;
begin
    if not public.is_link_admin() then
        raise exception 'Not authorized';
    end if;

    update public.links
    set tag = p_to
    where lower(tag) = lower(p_from);

    get diagnostics changed = row_count;
    return changed;
end;
$$;

revoke all on function public.retag_links(text, text) from public;
grant execute on function public.retag_links(text, text) to authenticated;

grant usage, select on sequence public.links_id_seq to anon, authenticated;

